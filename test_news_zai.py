import os
import requests
from bs4 import BeautifulSoup
from openai import OpenAI

# -----------------------------
# تنظیمات
# -----------------------------

NEWS_URL = "https://www.bbc.co.uk/sport/football/articles/cdx7x90dxywo?at_medium=RSS&at_campaign=rss"

client = OpenAI(
    api_key=os.environ["ZAI_API_KEY"],
    base_url="https://api.z.ai/api/paas/v4/"
)

# -----------------------------
# دریافت متن کامل خبر
# -----------------------------

print("در حال دریافت متن کامل خبر...")

headers = {
    "User-Agent": "Mozilla/5.0"
}

response = requests.get(
    NEWS_URL,
    headers=headers,
    timeout=30
)

response.raise_for_status()

soup = BeautifulSoup(response.text, "html.parser")

# حذف بخش‌های غیرضروری
for element in soup([
    "script",
    "style",
    "nav",
    "footer",
    "header",
    "aside"
]):
    element.decompose()

# پیدا کردن متن پاراگراف‌های خبر
paragraphs = []

for p in soup.find_all("p"):
    text = p.get_text(" ", strip=True)

    if len(text) >= 30:
        paragraphs.append(text)

news_text = "\n\n".join(paragraphs)

print(f"تعداد کاراکترهای متن دریافت‌شده: {len(news_text)}")

if len(news_text) < 500:
    raise Exception("متن کامل خبر به‌درستی دریافت نشد.")

# -----------------------------
# پرامپت بازنویسی
# -----------------------------

prompt = f"""
تو ویراستار و نویسنده حرفه‌ای اخبار فوتبال برای یک کانال خبری فارسی هستی.

متن کامل گزارش منبع در پایین قرار دارد.

وظیفه تو این است که از روی همین گزارش، یک خبر فارسی روان، طبیعی و حرفه‌ای برای انتشار در تلگرام بنویسی.

قوانین بسیار مهم:

1. متن را ترجمه تحت‌اللفظی نکن.
2. لحن باید شبیه خبر ورزشی حرفه‌ای فارسی باشد، نه متن ماشینی.
3. یک تیتر کوتاه، جذاب و خبری بنویس.
4. بعد از تیتر، یک خلاصه 3 تا 5 جمله‌ای بنویس.
5. خلاصه نباید صرفاً تیتر را دوباره تکرار کند.
6. در خلاصه، جزئیات مهم گزارش را اضافه کن؛ مانند:
   - علت اتفاق
   - اظهارات افراد
   - جزئیات قرارداد یا مذاکرات
   - وضعیت فعلی
   - واکنش باشگاه یا بازیکن
   - اتفاقات بعدی
   البته فقط در صورتی که این اطلاعات در متن منبع وجود داشته باشند.
7. مهم‌ترین اطلاعات را در چند جمله اول بیاور.
8. از اطلاعات موجود در متن منبع استفاده کن و چیزی از خودت اضافه نکن.
9. اگر موضوعی در متن منبع مشخص نیست، درباره آن حدس نزن.
10. نام بازیکنان، مربیان و باشگاه‌ها را به شکل رایج و درست فارسی بنویس.
11. از عبارت‌های خشک و ترجمه‌ای مثل «به اعتبار قرارداد اعتراض می‌کند» تا حد امکان پرهیز کن و جمله را به شکل طبیعی فارسی بنویس.
12. تیتر و متن نباید یکدیگر را تکرار کنند.
13. از ایموجی استفاده نکن.
14. هیچ مقدمه، توضیح یا نظری درباره فرایند کارت نده.
15. فقط تیتر و متن خبر را تحویل بده.

فرمت خروجی دقیقاً:

تیتر

متن خبر

متن کامل گزارش منبع:
--------------------

{news_text}

--------------------
"""

# -----------------------------
# ارسال به Z.AI
# -----------------------------

print("در حال ارسال متن کامل خبر به Z.AI...")

result = client.chat.completions.create(
    model="glm-4.7-flash",
    messages=[
        {
            "role": "user",
            "content": prompt
        }
    ]
)

print()
print("========== نتیجه بازنویسی ==========")
print(result.choices[0].message.content)
print("====================================")
