import os
import requests
from bs4 import BeautifulSoup
from google import genai

NEWS_URL = "https://www.bbc.co.uk/sport/football/articles/cdx7x90dxywo?at_medium=RSS&at_campaign=rss"

print("در حال دریافت خبر...")

response = requests.get(
    NEWS_URL,
    headers={"User-Agent": "Mozilla/5.0"},
    timeout=30
)

response.raise_for_status()

soup = BeautifulSoup(response.text, "html.parser")

for tag in soup(["script", "style", "nav", "footer", "header", "aside"]):
    tag.decompose()

paragraphs = []

for p in soup.find_all("p"):
    text = p.get_text(" ", strip=True)

    if len(text) >= 40:
        paragraphs.append(text)

news_text = "\n\n".join(paragraphs)

print(f"تعداد کاراکترهای متن دریافت‌شده: {len(news_text)}")

client = genai.Client(
    api_key=os.environ["GEMINI_API_KEY"]
)

prompt = f"""
نقش تو: ویراستار حرفه‌ای اخبار فوتبال برای یک کانال خبری فارسی.

وظیفه:
از متن منبع زیر، یک خبر فارسی کوتاه، روان و دقیق بنویس.

قواعد قطعی:

1. فقط از اطلاعات موجود در متن منبع استفاده کن.
از دانش قبلی، حدس، استنباط یا اطلاعات بیرونی استفاده نکن.

2. هیچ واقعیتی را تغییر نده. به‌خصوص:
- وضعیت قراردادها
- اعداد و تاریخ‌ها
- نام افراد و باشگاه‌ها
- نقل‌قول‌ها
- تصمیم دادگاه‌ها و نهادها
- علت و نتیجه اتفاقات

3. میزان قطعیت متن منبع را حفظ کن.
اگر منبع می‌گوید:
«ادعا می‌کند»، «گزارش شده»، «منابع گفته‌اند»،
«به نظر می‌رسد» یا «هنوز تأیید نشده»،
تو نیز نباید آن را به یک واقعیت قطعی تبدیل کنی.

4. روابط بین اتفاقات را تغییر نده.
اگر منبع دو اتفاق جداگانه را بیان کرده، آنها را به رابطه علت و معلولی تبدیل نکن.

5. فقط اطلاعاتی را استفاده کن که مستقیماً به موضوع اصلی خبر مربوط هستند.
بخش‌های فرعی، اخبار دیگر، مطالب مرتبط و حاشیه‌های صفحه را نادیده بگیر.

6. خروجی شامل:
- یک تیتر خبری کوتاه و طبیعی
- یک پاراگراف 4 تا 6 جمله‌ای

7. تیتر نباید صرفاً ترجمه یا تکرار جمله اول باشد.

8. هر جمله باید اطلاعات تازه‌ای نسبت به تیتر یا جمله‌های قبلی اضافه کند.

9. مهم‌ترین اطلاعات را در ابتدای متن قرار بده.

10. از ترجمه تحت‌اللفظی پرهیز کن، اما هنگام روان‌سازی فارسی معنای اصلی را تغییر نده.

11. متن باید طبیعی و شبیه خبر ورزشی حرفه‌ای فارسی باشد؛
نه ماشینی، نه ادبی و نه محاوره‌ای.

12. از اغراق، صفت‌های غیرضروری، تحلیل شخصی و پیش‌بینی استفاده نکن.

13. اگر اطلاعات کافی برای بیان یک ادعا وجود ندارد،
آن ادعا را حذف کن؛ هرگز برای کامل‌تر شدن خبر چیزی اضافه نکن.

14. ایموجی، هشتگ، مقدمه، توضیح درباره نحوه کار یا نظر شخصی ننویس.

15. فقط خبر نهایی را تحویل بده.

فرمت خروجی:

تیتر

متن خبر

متن منبع:
--------------------
{news_text}
--------------------
"""

print("در حال ارسال متن کامل خبر به Gemini...")

response = client.models.generate_content(
    model="gemini-3.5-flash-lite",
    contents=prompt
)

print()
print("========== نتیجه Gemini ==========")
print(response.text)
print("==================================")
